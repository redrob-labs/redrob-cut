#!/usr/bin/env python3
"""Generate crates/ui-egui/src/redrob_tokens.rs from the Redrob design system's native token header.

    python3 scripts/gen_redrob_tokens.py /path/to/redrob-ui/dist/native/redrob_tokens.h

The header is redrob-ui's own generated export (`tools/generate/tokens.js` from `tokens.css`): the
same numbers the web gets, resolved through the same var() chains. This script only changes their
spelling to Rust. The output records the header's SHA-256 so a stale copy is visible in review.
"""
import hashlib
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/ui-egui/src/redrob_tokens.rs"
LINE = re.compile(r"constexpr uint32_t k(\w+) = 0x([0-9A-Fa-f]{8});\s*// (--[\w-]+)")


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"(?<=[A-Za-z])([0-9])", r"_\1", s)
    return s.upper()


def main() -> None:
    src = pathlib.Path(sys.argv[1])
    text = src.read_text()
    sha = hashlib.sha256(text.encode()).hexdigest()
    spaces: dict[str, list[tuple[str, str, str]]] = {}
    current = None
    for line in text.splitlines():
        m = re.match(r"namespace (light|dark) \{", line.strip())
        if m:
            current = m.group(1)
            spaces[current] = []
            continue
        m = LINE.search(line)
        if m and current:
            spaces[current].append((snake(m.group(1)), m.group(2).upper(), m.group(3)))
    if set(spaces) != {"light", "dark"}:
        sys.exit("error: expected a light and a dark namespace")
    out = [
        "//! Redrob design tokens as egui colours, both themes. GENERATED by",
        "//! `scripts/gen_redrob_tokens.py` from redrob-ui's `dist/native/redrob_tokens.h`; do not edit.",
        f"//! Source SHA-256: {sha}",
        "#![allow(dead_code)]",
        "",
        "use egui::Color32;",
        "",
        "/// `0xAARRGGBB` to an egui colour (premultiplied, as egui stores it).",
        "const fn argb(v: u32) -> Color32 {",
        "    let a = (v >> 24) as u8;",
        "    let (r, g, b) = ((v >> 16) as u8, (v >> 8) as u8, v as u8);",
        "    if a == 255 { Color32::from_rgb(r, g, b) } else { Color32::from_rgba_unmultiplied_const(r, g, b, a) }",
        "}",
        "",
    ]
    for space in ("light", "dark"):
        out.append(f"pub mod {space} {{")
        out.append("    use super::{Color32, argb};")
        for name, hexv, css in spaces[space]:
            out.append(f"    /// `{css}`")
            out.append(f"    pub const {name}: Color32 = argb(0x{hexv});")
        out.append("}")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT} ({sum(len(v) for v in spaces.values())} colours)")


if __name__ == "__main__":
    main()
